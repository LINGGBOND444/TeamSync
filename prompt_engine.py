def build_user_prompt(transcript: str, retry_hint: str = "") -> str:
    """拼接用户消息，包含会议记录和可选的重试提示。"""
    base = f"请处理以下会议记录，生成任务列表：\n会议记录：\n{transcript}"
    if retry_hint:
        base += f"\n\n{retry_hint}"
    return base + "\n直接输出JSON数组，不要带任何markdown代码块标记。"
